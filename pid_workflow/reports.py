def _md_table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
    return "\n".join(out)


def _cite(p: Any) -> str:
    if p.origin == "source":
        return f"p.{p.page} §{p.section}"
    return f"rule `{p.rule}`"


# -------------------------------------------------------------------------- proposals
def proposals_md(topo: Topology) -> str:
    gen = [(o, oid) for oid, o in topo.objects().items() if o.provenance.origin == "generated" and o.provenance.status
           and not isinstance(o, type(None))]
    by_rule: dict[str, list[Any]] = defaultdict(list)
    for oid, o in topo.objects().items():
        p = o.provenance
        if p.origin != "generated" or oid.startswith(("mod.",)):
            continue
        kind = type(o).__name__
        if kind in ("ProcessLine", "Signal"):
            continue  # lines are consequences of the inserted components; they are summarised below
        by_rule[p.rule or "?"].append(o)
    lines = ["# Proposed additions pending review", "",
             "Everything below was created by a project rule and is `pending_review`. "
             "Approve with `pid review <project> --approve-rule <rule>` or per id; reject with `--reject <id>`.", ""]
    pend = sum(1 for _, o in [(None, o) for o in topo.objects().values()] if o.provenance.origin == "generated" and o.provenance.status == "pending_review")
    lines.append(f"**{pend} generated objects are pending review** "
                 f"({sum(1 for o in topo.objects().values() if o.provenance.origin == 'generated' and o.provenance.status == 'approved')} approved).")
    lines.append("")
    for rule in sorted(by_rule):
        items = sorted(by_rule[rule], key=lambda o: (getattr(o, "tag", None) or "~", o.id))
        lines += [f"## `{rule}` — {len(items)} object(s)", ""]
        rows = []
        for o in items:
            tag = getattr(o, "tag", None) or "—"
            what = o.name or o.id
            tech = ""
            if hasattr(o, "technology_status"):
                tech = "generic (technology to be selected)" if o.technology_status == "unspecified_generic" else (o.technology or o.model_class)
            rows.append([f"`{tag}`", what, tech, ", ".join(o.provenance.triggers[:3]), o.provenance.status or ""])
        lines += [_md_table(["Tag (proposed)", "Item", "Technology", "Triggered by", "Status"], rows), ""]
    splits = [m for m in topo.modifications if m.field == "split"]
    lines += ["## Source lines split to insert components", "",
              f"{len(splits)} source lines were split; every child line keeps its service and properties (`split_from` points to the source line).", ""]
    mods = [m for m in topo.modifications if m.field in ("tag", "nozzles", "loop_id")]
    if mods:
        lines += ["## Changes to source objects (source value preserved)", "",
                  _md_table(["Object", "Field", "Source value", "Proposed", "Rule"], [[f"`{m.object_id}`", m.field, str(m.old), str(m.new), f"`{m.provenance.rule}`"] for m in mods]), ""]
    return "\n".join(lines)


# -------------------------------------------------------------------- unresolved
def unresolved_md(topo: Topology) -> str:
    open_ = [u for u in topo.unresolved_requirements if u.status == "open"]
    lines = ["# Unresolved requirements", "",
             "Values, selections and decisions the specification does not give. They were **preserved, not assumed**. "
             "(Design pressures, relief sizing, safety thresholds, valve failure positions, material classes, nozzle sizes and instrument ranges are never invented.)", "",
             f"**{len(open_)} open point(s).**", ""]
    order = ["conflict", "ambiguity", "selection", "missing_value", "scope"]
    titles = {"conflict": "Conflicts inside the specification", "ambiguity": "Ambiguities (modelled one way, to be confirmed)",
              "selection": "Open selections", "missing_value": "Missing values", "scope": "Out of scope / future"}
    n = 0
    for cat in order:
        items = [u for u in open_ if u.category == cat]
        if not items:
            continue
        lines += [f"## {titles[cat]}", ""]
        for u in items:
            n += 1
            aff = ", ".join(f"`{a}`" for a in u.affects[:8]) + (f" … (+{len(u.affects) - 8})" if len(u.affects) > 8 else "")
            lines += [f"### {n}. `{u.id}`", "", u.description, "",
                      f"- **Source:** {_cite(u.provenance)}" + (f" — “{u.provenance.quote}”" if u.provenance.quote else ""),
                      f"- **Affects:** {aff or '—'}"]
            if u.question:
                lines.append(f"- **Question:** {u.question}")
            if u.needed_for:
                lines.append(f"- **Needed for:** {u.needed_for}")
            lines.append("")
    return "\n".join(lines)


# ----------------------------------------------------------------- assumptions
def assumptions_md(topo: Topology, policy: Policy) -> str:
    notes = interpreted_notes(topo)
    lines = ["# Assumptions, interpretations and conventions", "",
             "## Engineering basis stated by the specification", ""]
    for b in topo.metadata.engineering_basis:
        pr = b["provenance"]
        lines.append(f"- {b['statement']} _(p.{pr['page']} §{pr['section']})_")
    lines += ["", "## Precedence and prerequisites", ""]
    for k, v in policy.generic["principles"].items():
        lines.append(f"- **{k.replace('_', ' ')}** — {v}")
    lines += ["", "## Interpretations made while reading the specification", "",
              "These are in `source_topology.json` with `basis: interpreted`; the diagram draws them like any other fact, so each needs engineering confirmation.", ""]
    lines.append(_md_table(["Objects", "Where", "Interpretation"], [[str(n), sect, txt] for txt, n, sect in notes]))
    lines += ["", "## Conventions chosen where the specification is silent", ""]
    tg = policy.generic["tagging"]
    lines += [
        f"- **Tags** are proposals (`tag_status: proposed`), ISA 5.1 style, numbered per prefix from {', '.join(f'{k} {v}' for k, v in tg['series'].items())}. "
        "Real tags from the specification are never overwritten and untagged source equipment stays untagged.",
        "- **Isolation valves use the `XV` prefix** because the specification's own example is “XV-201 pour vanne d'isolement”, "
        "even though ISA 5.1 would normally call a manual valve `HV`. The project example takes precedence over the generic convention.",
        f"- **Check valves use `NRV`**: {tg['notes']['NRV']}",
        "- **Loop numbers** are shared: the header PT, its PIC and the PCV of one loop carry the same number.",
        "- **Valve technology** is never chosen: unspecified valves use the explicit generic class "
        f"`{policy.generic['valve_defaults']['generic_class']}` with the type name “technology to be selected” (see unresolved requirement `ur.gen.valve_technology`).",
        "- **Control loop**: only the boiler back-up loop (explicit 7.5 bar eff. setpoint) is instrumented as measurement → controller → final element. "
        "A transmitter alone never creates a controller; the two spill valves have no stated controlled variable or setpoint and stay open points.",
        "- **Existing equipment** is included in the capacitive-equipment rule (drain, vent, level transmitter); each such proposal says to verify the already installed devices.",
        "",
    ]
    return "\n".join(lines)


# ----------------------------------------------------------------------- modes
def modes_md(topo: Topology, policy: Policy) -> str:
    en = Enricher(topo, policy)
    lines = ["# Operating modes", "",
             "States are shown only where the specification states them. “—” means the specification does not say.", ""]
    modes = topo.operating_modes
    for m in modes:
        lines += [f"## {m.name} (`{m.id}`)", "", m.description, "", f"_Source: {_cite(m.provenance)}_", ""]
        for r in m.requirements:
            tg = ", ".join(f"`{t.ref}:{t.port}`" for t in r.targets)
            lines.append(f"- **{r.action}** — {r.text}" + (f" ({tg})" if tg else ""))
        lines.append("")
    # valve matrix: isolation valves located by tracing from the targeted nozzles
    rows: dict[str, dict[str, str]] = {}
    for m in modes:
        for r in m.requirements:
            if r.action != "isolate":
                continue
            for t in r.targets:
                if t.ref not in en.eq:
                    continue
                chain, _, _ = en.trace(t.ref, t.port)
                v = next((c for c in chain if c.function == "isolation"), None)
                if v is None:
                    continue
                key = f"{v.tag or v.id} — {v.name}"
                rows.setdefault(key, {})[m.id] = "closed"
    if rows:
        lines += ["## Isolation valves per mode", "",
                  _md_table(["Valve"] + [m.name for m in modes], [[k] + [rows[k].get(m.id, "—") for m in modes] for k in sorted(rows)]), ""]
    return "\n".join(lines)


# --------------------------------------------------------------------- enrichment
def enrichment_md(log: list[LogEntry], run_no: int | None = None) -> str:
    c = Counter((e.rule, e.action) for e in log)
    rules = sorted({e.rule for e in log})
    lines = ["# Enrichment log", "", "What each rule did on its last run. “reused” means the requirement was already satisfied (nothing duplicated).", ""]
    rows = [[f"`{r}`"] + [str(c.get((r, a), 0)) for a in ("added", "reused", "blocked", "skipped")] for r in rules]
    lines += [_md_table(["Rule", "Added", "Reused", "Blocked (prerequisite missing)", "Skipped"], rows), ""]
    blocked = [e for e in log if e.action in ("blocked", "skipped")]
    if blocked:
        lines += ["## Blocked or skipped", ""] + [f"- `{e.rule}` — {e.message}" for e in blocked] + [""]
    return "\n".join(lines)


# ------------------------------------------------------------------------ export
def export_md(rep: ExportReport, xml_name: str) -> str:
    lines = ["# Export to DEXPI Proteus XML — what is and is not carried over", "",
             f"File: `{xml_name}` (Proteus 4.1.1, written with pyDEXPI 1.2.0).", "",
             "## Contents", "", _md_table(["Element", "Count"], [[k, str(v)] for k, v in sorted(rep.counts.items())]), "",
             "## Limitations", ""]
    lines += [f"{i}. {t}" for i, t in enumerate(rep.limitations, 1)]
    lines += ["",
              "## pyDEXPI 1.2.0 findings",
              "",
              "- The stock Proteus **exporter** writes only equipment, nozzles and metadata. Piping networks and instrumentation are written by `pid_workflow/proteus_ext.py`, "
              "which plugs into pyDEXPI's exporter framework and follows the structure the pyDEXPI **parser** reads. The result is re-loaded with pyDEXPI to prove it parses.",
              "- `PlantModelExporter` reads `self.metadata_exporter` even when a model has no metadata (AttributeError); the model therefore always carries a `MetaData` object.",
              "- The pyDEXPI **loader** ignores custom attributes and `FromNode`/`ToNode` indices; those are verified at XML level (see the round-trip report).",
              "- `equipmentDescription` (a multi-language string) is not written by the stock exporter; the description is kept in the custom attribute `Name`.",
              ""]
    if rep.native_attributes:
        lines += ["## Quantities mapped to native DEXPI attributes", ""] + [f"- {a}" for a in sorted(set(rep.native_attributes))[:12]] + [""]
    if rep.custom_only_attributes:
        lines += ["## Attributes carried as text custom attributes", "", ", ".join(f"`{a}`" for a in sorted(rep.custom_only_attributes)), ""]
    return "\n".join(lines)


# ----------------------------------------------------------------------- summary
def summary_md(topo: Topology, val: ValidationReport, rt: RoundTripReport | None, qa: dict[str, list[str]], facts: dict[str, Any]) -> str:
    md = topo.metadata
    lines = [f"# {md.title}", "", f"Drawing `{md.drawing_id}` · revision {md.revision} · **DRAFT — pending engineering review**", "",
             f"Source: `{md.source_documents[0]['file']}` ({md.source_documents[0]['pages']} pages). The AI extracted it into `source_topology.json` (read-only snapshot, "
             f"sha256 `{(md.source_snapshot_sha256 or '')[:12]}…`); rules produced `working_topology.json`.", "",
             "## Status", "",
             f"- Structural validation: **{'PASS' if val.ok else 'FAIL'}** ({len(val.errors)} errors, {len(val.warnings)} warnings)",
             f"- Proteus XML round trip: **{'PASS' if rt and rt.ok else 'FAIL'}**" + (f" ({len(rt.checks)} checks)" if rt else ""),
             f"- Layout checks: **{'clean' if not any(qa.values()) else 'issues'}** ({sum(len(v) for v in qa.values())} geometric problems on {len(qa)} sheets)", "",
             "## The model", "",
             _md_table(["Item", "Count"], [[k, str(v)] for k, v in facts.items()]), "",
             "## What to review first", "",
             "1. `reports/unresolved_requirements.md` — conflicts and ambiguities in the specification (start with the first section).",
             "2. `reports/proposals.md` — everything the rules added, grouped by rule, all pending.",
             "3. `reports/assumptions.md` — interpretations and conventions that need a yes/no.",
             "4. `output/pid_review_draft.pdf` — the drawings; orange = proposed, red dots = open points.", "",
             "## Files", "",
             "| File | Purpose |", "|---|---|",
             "| `source_topology.json` | unchanged snapshot of the extracted source facts, with page/section provenance |",
             "| `working_topology.json` | active graph: source + proposed additions (provenance: rule, triggers, explanation, status) |",
             "| `output/pid_review_draft.pdf` | review set: cover, overview, one sheet per area, review tables |",
             "| `output/pid_draft.proteus.xml` | DEXPI Proteus XML (pyDEXPI) |",
             "| `reports/validation.md` · `roundtrip.md` · `enrichment.md` · `export_limitations.md` · `operating_modes.md` · `layout.md` | checks and logs |", ""]
    return "\n".join(lines)


def layout_md(qa: dict[str, list[str]], scales: dict[str, float], sheet_qa: list[str] | None = None, sheet_scale: float = 0.0) -> str:
    lines = ["# Layout checks", "", "Geometric checks on the computed drawings (no coordinates are stored in the topology).", ""]
    if sheet_qa is not None:
        lines += ["## One-sheet P&ID (A0)", "", f"Drawing scale on the A0 field: {sheet_scale:.2f} (1.00 = symbol and text sizes as designed). "
                  f"Problems: {len(sheet_qa)}.", ""]
        lines += [f"- {m}" for m in sheet_qa]
        lines += ["", "## Review pack (A3 sheets per area)", ""]
    rows = [[sid, f"{scales.get(sid, 0):.2f}", str(len(v))] for sid, v in qa.items()]
    lines += [_md_table(["Sheet", "Drawing scale on A3", "Problems"], rows), ""]
    for sid, v in qa.items():
        for m in v:
            lines.append(f"- {m}")
    return "\n".join(lines)
